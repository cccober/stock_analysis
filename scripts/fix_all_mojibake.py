def fix_mojibake_in_file(filepath):
    """修复文件中的 Mojibake 问题"""
    with open(filepath, 'rb') as f:
        raw = f.read()

    # 跳过 BOM
    if raw.startswith(b'\xef\xbb\xbf'):
        raw = raw[3:]

    # 清理多余的 \r
    raw = raw.replace(b'\r\r\r\r\n', b'\n').replace(b'\r\r\n', b'\n').replace(b'\r\n', b'\n')

    content = raw.decode('utf-8')

    # 检查是否包含 GBK 乱码模式的字符
    garbled_chars = set('ÃÂÀÁÈÉÊËÌÍÎÏÐÑÒÓÔÕÖØÙÚÛÜÝÞßàáâãäåæçèéêëìíîïðñòóôõöøùúûüýþÿ')
    has_garbled = any(c in content for c in garbled_chars)

    if not has_garbled:
        print(f"未发现乱码: {os.path.basename(filepath)}")
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        return False

    print(f"发现乱码，开始修复...")
    fixed_content = content
    fix_count = 0

    # 应用映射表修复
    for garbled, correct in GARBLED_PATTERNS.items():
        if garbled in fixed_content:
            fixed_content = fixed_content.replace(garbled, correct)
            fix_count += 1

    # 尝试用 GBK 解码的方法修复剩余乱码
    # 将 UTF-8 字节解码为 GBK 会得到正确的中文
    try:
        # 找到所有包含乱码的行
        lines = fixed_content.split('\n')
        fixed_lines = []
        for line in lines:
            if any(c in line for c in garbled_chars):
                # 尝试修复这一行
                try:
                    # 将行编码为 UTF-8 字节，然后解码为 GBK
                    line_bytes = line.encode('utf-8')
                    fixed_line = line_bytes.decode('gbk')
                    fixed_lines.append(fixed_line)
                except:
                    fixed_lines.append(line)
            else:
                fixed_lines.append(line)
        fixed_content = '\n'.join(fixed_lines)
    except:
        pass

    # 再次检查是否还有乱码
    still_has_garbled = any(c in fixed_content for c in garbled_chars)

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(fixed_content)

    if still_has_garbled:
        print(f"部分乱码已修复，但仍有残留: {os.path.basename(filepath)}")
    else:
        print(f"乱码修复完成: {os.path.basename(filepath)}")

    return True

